export function runScenarioSimulation(
  leadTimeMultiplier: number,
  safetyStockMultiplier: number,
  demandShockPct: number,
  skus: SKUInventoryItem[]
): ScenarioSimulationResult {
  // Baseline stockout rate: ~2.1%
  // Baseline service level: ~97.9%
  const leadTimeImpact = (leadTimeMultiplier - 1.0) * 4.5;
  const safetyStockBuffer = (safetyStockMultiplier - 1.0) * -3.8;
  const demandShockImpact = (demandShockPct / 100) * 5.2;

  const projectedStockoutRisk = Math.max(0.2, +(2.1 + leadTimeImpact + safetyStockBuffer + demandShockImpact).toFixed(2));
  const projectedServiceLevel = Math.min(99.9, +(100 - projectedStockoutRisk).toFixed(2));
  
  // Holding cost change scales with safety stock multiplier
  const holdingCostDeltaPct = +((safetyStockMultiplier - 1.0) * 18.5 + (demandShockPct * 0.1)).toFixed(1);
  const recommendedSafetyStockDeltaPct = +(
    (leadTimeMultiplier - 1.0) * 22.0 +
    (demandShockPct > 0 ? demandShockPct * 0.8 : 0)
  ).toFixed(1);

  // Critical SKU count calculation
  const criticalSKUCount = skus.filter((sku) => {
    const adjustedDemand = sku.dailyDemand * (1 + demandShockPct / 100);
    const adjustedLeadTime = sku.leadTimeDays * leadTimeMultiplier;
    const effectiveSafetyStock = sku.safetyStock * safetyStockMultiplier;
    const dynamicROP = adjustedDemand * adjustedLeadTime + effectiveSafetyStock;
    return sku.currentStock <= dynamicROP;
  }).length;

  return {
    projectedStockoutRisk,
    projectedServiceLevel,
    holdingCostDeltaPct,
    recommendedSafetyStockDeltaPct,
    criticalSKUCount,
  };
}
